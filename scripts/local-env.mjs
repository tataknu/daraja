#!/usr/bin/env node
// Writes apps/web/.env.local for the local stack (Supabase in Docker + OpenAI for the AI adapter).
// Run via `make env`. The file is git-ignored (*.local). Keeps an OPENAI_API_KEY/AI_* already in it.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const ENV_FILE = "apps/web/.env.local";

function supabaseStatus() {
  const out = execFileSync("npx", ["--yes", "supabase@2", "status", "-o", "json"], {
    cwd: "packages/db",
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  });
  return JSON.parse(out.slice(out.indexOf("{"), out.lastIndexOf("}") + 1));
}

function readEnv(path) {
  if (!existsSync(path)) return {};
  return Object.fromEntries(
    readFileSync(path, "utf8")
      .split("\n")
      .filter((l) => /^[A-Z0-9_]+=/.test(l))
      .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]),
  );
}

const s = supabaseStatus();
const prev = readEnv(ENV_FILE);
const openaiKey = prev.OPENAI_API_KEY || process.env.OPENAI_API_KEY || "";

const env = {
  // Browser (baked into the bundle by Vite)
  VITE_SUPABASE_URL: s.API_URL,
  VITE_SUPABASE_PUBLISHABLE_KEY: s.ANON_KEY,
  VITE_SUPABASE_PROJECT_ID: "local",
  // Server
  SUPABASE_URL: s.API_URL,
  SUPABASE_PUBLISHABLE_KEY: s.ANON_KEY,
  SUPABASE_SERVICE_ROLE_KEY: s.SERVICE_ROLE_KEY,
  // Webhooks and cron, with local-only secrets
  PHASE2_ENABLED: "true",
  POSTMARK_INBOUND_USER: "local",
  POSTMARK_INBOUND_PASS: "local-postmark-pass",
  TWILIO_AUTH_TOKEN: "local-twilio-token",
  LOVABLE_CRON_SECRET: "local-cron-secret",
  // AI: OpenAI directly instead of Lovable's gateway
  AI_GATEWAY_URL: prev.AI_GATEWAY_URL || "https://api.openai.com/v1/responses",
  AI_MODEL: prev.AI_MODEL || "gpt-5.4-mini",
  OPENAI_API_KEY: openaiKey,
};

writeFileSync(
  ENV_FILE,
  "# Generated by `make env` for the local stack. Git-ignored; safe to edit.\n" +
    Object.entries(env)
      .map(([k, v]) => `${k}=${v}`)
      .join("\n") +
    "\n",
);
console.log(`wrote ${ENV_FILE} (Supabase ${s.API_URL}, AI model ${env.AI_MODEL})`);
if (!openaiKey) console.warn(`! OPENAI_API_KEY is empty: add it to ${ENV_FILE} or run: OPENAI_API_KEY=sk-... make env`);
