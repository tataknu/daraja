// Turns the eval's cached review analyses into the analyses the demo stores with its sample
// reviews, so loading the samples costs no tokens: the same model calls serve the eval and the demo.
// Usage: bun src/export-sample-analyses.ts [--model <id>] [--effort <level>]
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { ReviewAnalysis } from "@daraja/engine/ai";
import { SAMPLE_REVIEWS } from "@daraja/engine/samples";
import { slug, type CacheEntry } from "./cache";

const arg = (name: string, fallback: string) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? (process.argv[i + 1] ?? fallback) : fallback;
};
const model = arg("model", "gpt-5.4-mini");
const effort = arg("effort", "low");
const dir = fileURLToPath(
  new URL(`../results/.cache/reviews/${slug(model)}__${slug(effort)}/`, import.meta.url),
);
const out = fileURLToPath(new URL("../../engine/src/samples/analyses.ts", import.meta.url));

// Newest entry per review: a prompt change leaves older entries behind under other keys.
const newest = new Map<string, CacheEntry<ReviewAnalysis>>();
for (const file of readdirSync(dir)) {
  const entry = JSON.parse(readFileSync(dir + file, "utf8")) as CacheEntry<ReviewAnalysis>;
  const seen = newest.get(entry.case_id);
  if (!seen || entry.created_at > seen.created_at) newest.set(entry.case_id, entry);
}
const byId = Object.fromEntries(
  SAMPLE_REVIEWS.flatMap((r) => {
    const e = newest.get(r.id);
    return e ? [[r.id, e.output]] : [];
  }),
);
const missing = SAMPLE_REVIEWS.filter((r) => !newest.has(r.id)).map((r) => r.id);

writeFileSync(
  out,
  `// Generated by \`bun run --filter @daraja/eval export-samples\` from the eval's cached answers.
// Model ${model}, reasoning effort ${effort}, ${new Date().toISOString().slice(0, 10)}. Don't edit by hand.
import type { ReviewAnalysis } from "../ai/types";

export const SAMPLE_ANALYSES: Record<string, ReviewAnalysis> = ${JSON.stringify(byId, null, 2)};
`,
);
console.log(
  `${Object.keys(byId).length} analyses written to samples/analyses.ts` +
    (missing.length ? `; missing (run the reviews suite first): ${missing.join(", ")}` : ""),
);
