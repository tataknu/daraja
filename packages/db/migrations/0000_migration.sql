CREATE TABLE public.contacts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  role text NOT NULL CHECK (role IN ('guest','host')),
  name text NOT NULL,
  email text UNIQUE,
  phone text UNIQUE,
  language text NOT NULL DEFAULT 'en',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.farm_settings (
  id int PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  host_id uuid REFERENCES public.contacts(id),
  slots text[] NOT NULL,
  max_per_slot int NOT NULL,
  price_per_person numeric NOT NULL,
  currency text NOT NULL,
  directions text NOT NULL
);
CREATE TABLE public.bookings (
  id int GENERATED BY DEFAULT AS IDENTITY (START WITH 14) PRIMARY KEY,
  guest_id uuid NOT NULL REFERENCES public.contacts(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'INCOMPLETE',
  date_from date, date_to date, slot text, party_size int,
  notes_original text, notes_translated text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.messages (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  direction text NOT NULL CHECK (direction IN ('in','out')),
  channel text NOT NULL CHECK (channel IN ('email','sms')),
  contact_id uuid REFERENCES public.contacts(id) ON DELETE CASCADE,
  booking_id int REFERENCES public.bookings(id) ON DELETE SET NULL,
  provider_msg_id text UNIQUE,
  thread_ref text,
  text_original text NOT NULL,
  lang text,
  text_translated text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.pending_prompts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_id int REFERENCES public.bookings(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('approve_booking','answer_question','confirm_cancellation','confirm_readback','ask_other_date')),
  options jsonb NOT NULL DEFAULT '{}'::jsonb,
  sent_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL DEFAULT now() + interval '48 hours',
  nudged_at timestamptz,
  resolved_at timestamptz,
  resolution text
);
CREATE TABLE public.decisions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  message_id uuid REFERENCES public.messages(id) ON DELETE CASCADE,
  intent text, confidence numeric, entities jsonb, model text,
  action_taken text, routed_to_human boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.feedback (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_id int REFERENCES public.bookings(id) ON DELETE SET NULL,
  text_original text NOT NULL, lang text, text_translated text,
  themes text[] NOT NULL DEFAULT '{}', sentiment text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.reminders_sent (
  booking_id int NOT NULL REFERENCES public.bookings(id) ON DELETE CASCADE,
  kind text NOT NULL,
  PRIMARY KEY (booking_id, kind)
);

